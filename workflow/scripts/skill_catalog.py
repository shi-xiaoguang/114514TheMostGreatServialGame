"""Shared deterministic metadata for the local, tool-neutral skill adapters."""

from __future__ import annotations

import json
from pathlib import Path
import re


VENDOR_RELATIVE = Path("workflow/vendor/godot-game-dev-studio")
EXPECTED_SKILLS = 189
MANAGER_ID = "robinson-godot-studio-adapters-v1"
MANIFEST_NAME = ".generated-by-robinson.json"


def frontmatter(text: str) -> dict[str, str]:
    """Read the scalar fields used by this pinned snapshot, without YAML code."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("Missing opening frontmatter fence")
    result = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return result
        match = re.match(r"^([a-zA-Z_-]+):\s*(.*?)\s*$", line)
        if match:
            value = match.group(2)
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            result[match.group(1)] = value
    raise ValueError("Missing closing frontmatter fence")


def build_index(root: Path) -> dict:
    lock = json.loads((root / "workflow/upstream-lock.json").read_text(encoding="utf-8-sig"))
    source = root / VENDOR_RELATIVE / "skills"
    entries = []
    for directory in sorted(source.iterdir()):
        if not directory.is_dir():
            continue
        name = directory.name
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError(f"Invalid skill directory name: {name!r}")
        fields = frontmatter((directory / "SKILL.md").read_text(encoding="utf-8-sig"))
        if not fields.get("name") or not fields.get("description"):
            raise ValueError(f"Missing skill name/description: {name}")
        entries.append({"id": name, "name": name, "description": fields["description"],
                        "source": (VENDOR_RELATIVE / "skills" / name / "SKILL.md").as_posix(),
                        "declared_name": fields["name"]})
    if len(entries) != EXPECTED_SKILLS:
        raise ValueError(f"Expected {EXPECTED_SKILLS} source skill directories, found {len(entries)}")
    return {"schema_version": 1, "upstream_commit": lock["commit"], "skills": entries}


def index_bytes(index: dict) -> bytes:
    return (json.dumps(index, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def adapter_bytes(skill: dict) -> bytes:
    # Three parents reaches the repository root both through tool junctions and
    # when the same file is read at workflow/skills/<id>/SKILL.md.
    description = json.dumps(skill["description"], ensure_ascii=False)
    text = f'''---
name: {skill["name"]}
description: {description}
---

<!-- Generated by {MANAGER_ID}; edit the source integration, then regenerate. -->

# {skill["name"]}

1. Read repository [CODEBUDDY.md](../../../CODEBUDDY.md), its team rules, and
   [PROJECT_STATUS.md](../../../PROJECT_STATUS.md) before applying this skill.
2. Open the complete upstream [SKILL.md](../../../{skill["source"]}) and follow
   the sections relevant to the current task. This adapter is only a route.
3. Resolve every upstream relative reference from the original upstream skill
   directory (`{Path(skill["source"]).parent.as_posix()}`), including `references/`,
   `scripts/`, `assets/`, and sibling skills. Do not resolve them from this adapter.
4. Run Godot against `game/project.godot`; keep workflow examples outside `game/`.
   Project rules and the user's current authorization take precedence over
   generic upstream examples and workflow assumptions.

Upstream frontmatter name: `{skill["declared_name"]}`. Local unique name: `{skill["name"]}`.
'''
    return text.encode("utf-8")


def generated_files(index: dict) -> dict[str, bytes]:
    return {f"{entry['id']}/SKILL.md": adapter_bytes(entry) for entry in index["skills"]}
